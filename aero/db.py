"""Oracle AI Database 23ai: VECTOR column + SQL similarity search (Module 6)."""
from __future__ import annotations

import array

import oracledb

from . import config

oracledb.defaults.fetch_lobs = False  # return CLOBs as plain str

DDL = f"""
CREATE TABLE doc_chunks (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source     VARCHAR2(300),
    doc_type   VARCHAR2(60),
    page       NUMBER,
    chunk_text CLOB,
    embedding  VECTOR({config.EMBED_DIM}, FLOAT32)
)
"""


def connect() -> oracledb.Connection:
    return oracledb.connect(
        user=config.ORACLE_USER, password=config.ORACLE_PASSWORD, dsn=config.ORACLE_DSN
    )


def init_schema(conn: oracledb.Connection) -> None:
    with conn.cursor() as cur:
        try:
            cur.execute(DDL)
        except oracledb.DatabaseError as exc:
            if exc.args[0].code != 955:  # ORA-00955: name already used (table exists)
                raise
        try:  # optional IVF index; tiny corpora do not need it
            cur.execute(
                "CREATE VECTOR INDEX doc_chunks_ivf ON doc_chunks(embedding) "
                "ORGANIZATION NEIGHBOR PARTITIONS DISTANCE COSINE"
            )
        except oracledb.DatabaseError:
            pass  # exists or unsupported: exact search still works


def _vec(v: list[float]) -> array.array:
    return array.array("f", v)


def replace_source(
    conn: oracledb.Connection,
    source: str,
    doc_type: str,
    rows: list[tuple[int, str, list[float]]],
) -> None:
    """Idempotent ingest: delete the source's old chunks, insert the new ones."""
    with conn.cursor() as cur:
        cur.execute("DELETE FROM doc_chunks WHERE source = :s", s=source)
        cur.executemany(
            "INSERT INTO doc_chunks (source, doc_type, page, chunk_text, embedding) "
            "VALUES (:1, :2, :3, :4, :5)",
            [(source, doc_type, page, text, _vec(vec)) for page, text, vec in rows],
        )
    conn.commit()


def search(
    conn: oracledb.Connection,
    query_vec: list[float],
    top_k: int = 4,
    doc_type: str | None = None,
) -> list[dict]:
    """Semantic search + ordinary relational filter in ONE SQL statement."""
    where = "WHERE doc_type = :dt" if doc_type else ""
    sql = (
        "SELECT source, doc_type, page, chunk_text, "
        "VECTOR_DISTANCE(embedding, :qv, COSINE) AS dist "
        f"FROM doc_chunks {where} "
        "ORDER BY dist FETCH FIRST :k ROWS ONLY"
    )
    params: dict = {"qv": _vec(query_vec), "k": int(top_k)}
    if doc_type:
        params["dt"] = doc_type
    with conn.cursor() as cur:
        cur.execute(sql, params)
        return [
            {"source": s, "doc_type": t, "page": p, "text": x, "distance": float(d)}
            for s, t, p, x, d in cur.fetchall()
        ]


def count_chunks(conn: oracledb.Connection) -> int:
    with conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM doc_chunks")
        return int(cur.fetchone()[0])
